/** Reproducible local web assets and previews. No CDN or browser-side transpiler. */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build, transform} from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ds = path.join(root, 'brand/design-system');
const modules = path.join(root, 'node_modules');
const walk = async dir => (await Promise.all((await fs.readdir(dir, {withFileTypes:true})).map(e => e.isDirectory() ? walk(path.join(dir,e.name)) : [path.join(dir,e.name)]))).flat();
async function write(file, value) { await fs.mkdir(path.dirname(file), {recursive:true}); await fs.writeFile(file,value); }
async function copy(from,to) { await write(to,await fs.readFile(from)); }
const banner = '// Generated by scripts/build-design-system.mjs. Do not edit.\n';
const opts = {bundle:true,minify:true,legalComments:'linked',target:['es2022'],logLevel:'warning'};
const files = await walk(ds);

// Shared runtime: exactly one React instance for all components and demos.
await build({...opts, stdin:{contents:'import React from "react"; import * as ReactDOM from "react-dom/client"; window.React=React; window.ReactDOM=ReactDOM;',resolveDir:root},outfile:path.join(ds,'dist/js/runtime.js'),define:{'process.env.NODE_ENV':'"production"'}});

// Fonts are versioned npm inputs; Latin includes German umlauts and ß.
let fontCss='/* Generated, self-hosted fonts. Licences in dist/licenses/. */\n';
for(const [slug,family,weights] of [['ibm-plex-sans','IBM Plex Sans',[400,500,600,700]],['geist-mono','Geist Mono',[400,500,600]]]){
 for(const weight of weights){
  const name=`${slug}-latin-${weight}-normal.woff2`;
  await copy(path.join(modules,'@fontsource',slug,'files',name),path.join(ds,'dist/fonts',name));
  fontCss+=`@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url("../fonts/${name}") format("woff2")}\n`;
 }
 await copy(path.join(modules,'@fontsource',slug,'LICENSE'),path.join(ds,'dist/licenses',`${slug}-LICENSE.txt`));
}
await write(path.join(ds,'dist/css/fonts.css'),fontCss);

// Include only Lucide glyphs mentioned in the sources, as self-contained SVG masks.
const iconNames = new Set(['circle-help']);
for(const f of files.filter(f=>/\.(jsx|html|js)$/.test(f)&&!f.includes(`${path.sep}dist${path.sep}`))){
 const text=await fs.readFile(f,'utf8');
 for(const match of text.matchAll(/["']([a-z][a-z0-9-]*)["']/g)) iconNames.add(match[1]);
}
const icons={};
for(const name of [...iconNames].sort()){
 try{const svg=await fs.readFile(path.join(modules,'lucide-static/icons',name+'.svg'),'utf8'); icons[name]='data:image/svg+xml,'+encodeURIComponent(svg);}
 catch(e){if(e.code!=='ENOENT')throw e;}
}
await write(path.join(ds,'dist/js/icons.js'),banner+'export const ICONS = '+JSON.stringify(icons)+';\n');
for(const [source,name] of [['lucide-static/LICENSE','lucide-LICENSE.txt'],['react/LICENSE','react-LICENSE.txt'],['react-dom/LICENSE','react-dom-LICENSE.txt'],['plotly.js-dist-min/LICENSE','plotly-LICENSE.txt']]) await copy(path.join(modules,source),path.join(ds,'dist/licenses',name));
await copy(path.join(modules,'plotly.js-dist-min/plotly.min.js'),path.join(ds,'dist/vendor/plotly.min.js'));

const components=(await walk(path.join(ds,'components'))).filter(f=>f.endsWith('.jsx')&&!f.endsWith('.preview.jsx')).sort();
await build({...opts,stdin:{contents:components.map(f=>`export * from ${JSON.stringify('./'+path.relative(ds,f).replaceAll('\\','/'))};`).join('\n'),resolveDir:ds},outfile:path.join(ds,'dist/js/components.js'),format:'iife',globalName:'StadtWerkeWesthafenDesignSystem_acd94c',plugins:[{name:'shared-react',setup(b){b.onResolve({filter:/^react$/},()=>({path:'react',namespace:'shared'}));b.onLoad({filter:/.*/,namespace:'shared'},()=>({contents:'export default window.React;'}));}}]});

for(const file of files.filter(f=>f.endsWith('.preview.jsx')||(/ui_kits[\\/]energie-cockpit[\\/].*\.jsx$/.test(f)))){
 const isPreview=file.endsWith('.preview.jsx');
 const output=isPreview?path.join(ds,'dist/previews',path.relative(ds,file).replace(/\.preview\.jsx$/,'.js')):path.join(ds,'dist/js',path.basename(file).replace('.jsx','.js'));
 const result=await transform(await fs.readFile(file,'utf8'),{loader:'jsx',format:'iife',target:'es2022',minify:true});
 await write(output,banner+result.code);
}
// Old direct chart-style paths remain supported, but are generated too.
await copy(path.join(ds,'dist/plotly/template.json'),path.join(ds,'assets/plotly/sww_plotly_template.json'));
await copy(path.join(ds,'dist/matplotlib/sww.mplstyle'),path.join(ds,'assets/plotly/sww_matplotlib.mplstyle'));
console.log(`Built ${components.length} components, ${Object.keys(icons).length} local icons, local fonts and all previews.`);
